/* ============================================================
   NEXORA — Import Tool
   Phase 5 Mass Import Engine. Reads whatever .html files the user
   selects from demos/ using the browser's File API (File.text() —
   a local read of a selected file, NOT fetch(), so this works
   identically whether the tool page itself is opened via a server
   or double-clicked directly). Generates a slug and title per file
   (from its <title> tag if present, otherwise its filename) and
   produces a single downloadable catalog — never a per-file JSON,
   matching the "copy file → paste into demos/ → run import" goal.
   ============================================================ */
(function () {
  "use strict";

  const input = document.getElementById("it-input");
  const chooseBtn = document.getElementById("it-choose-btn");
  const resultsSection = document.getElementById("it-results");
  const emptyState = document.getElementById("it-empty");
  const summary = document.getElementById("it-summary");
  const tableBody = document.getElementById("it-table-body");
  const downloadBtn = document.getElementById("it-download-btn");

  chooseBtn.addEventListener("click", () => input.click());

  function slugify(name) {
    return name
      .toLowerCase()
      .replace(/\.[^/.]+$/, "") // strip extension
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/(^-|-$)/g, "");
  }

  function humanize(slug) {
    return slug.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());
  }

  async function extractTitle(file, fallbackSlug) {
    try {
      const text = await file.text();
      const match = text.match(/<title[^>]*>([^<]*)<\/title>/i);
      const found = match && match[1].trim();
      return found || humanize(fallbackSlug);
    } catch {
      return humanize(fallbackSlug);
    }
  }

  function tableRowHTML(entry) {
    return `<tr><td>${entry.filename}</td><td>${entry.title}</td><td><code>${entry.slug}</code></td></tr>`;
  }

  /**
   * The empty state and the results section are mutually exclusive —
   * exactly one is ever visible. Routing every visibility change
   * through this one function (instead of setting .hidden on each
   * element separately at each call site) makes that guarantee
   * structural rather than a convention someone could break by
   * editing one branch and forgetting the other.
   * @param {"empty"|"results"} mode
   */
  function setState(mode) {
    emptyState.hidden = mode !== "empty";
    resultsSection.hidden = mode !== "results";
  }

  input.addEventListener("change", async () => {
    const htmlFiles = Array.from(input.files).filter((f) => f.name.toLowerCase().endsWith(".html"));

    if (!htmlFiles.length) {
      setState("empty");
      return;
    }

    const seenSlugs = new Set();
    const entries = [];

    for (const file of htmlFiles) {
      let slug = slugify(file.name);
      // Guard against two files producing the same slug (e.g.
      // "My Demo.html" and "my-demo.html") — keep every file visible
      // rather than silently dropping one.
      let uniqueSlug = slug;
      let suffix = 2;
      while (seenSlugs.has(uniqueSlug)) {
        uniqueSlug = `${slug}-${suffix}`;
        suffix += 1;
      }
      seenSlugs.add(uniqueSlug);

      const title = await extractTitle(file, uniqueSlug);
      const modified = file.lastModified ? new Date(file.lastModified).toISOString().slice(0, 10) : new Date().toISOString().slice(0, 10);

      entries.push({
        slug: uniqueSlug,
        title,
        filename: file.name,
        createdAt: modified,
        updatedAt: modified,
      });
    }

    entries.sort((a, b) => a.title.localeCompare(b.title));

    tableBody.innerHTML = entries.map(tableRowHTML).join("");
    summary.textContent = `${entries.length} demo${entries.length === 1 ? "" : "s"} detected in demos/`;
    setState("results");

    const catalog = {
      version: "1.0.0",
      updatedAt: new Date().toISOString().slice(0, 10),
      note: "Generated by tools/import.html by scanning demos/. Do not hand-edit — reopen the import tool and re-run instead.",
      count: entries.length,
      demos: entries,
    };

    const blob = new Blob([JSON.stringify(catalog, null, 2)], { type: "application/json" });
    const url = URL.createObjectURL(blob);
    downloadBtn.href = url;
  });
})();
